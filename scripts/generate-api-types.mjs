/**
 * Generates TypeScript types from the backend's API files (DEC-228).
 * Reads ../docs/api/*.openapi.yaml and writes types/api/<name>.ts (one per file).
 * The output is committed, so Vercel never needs the docs folder.
 * Run: npm run api:types
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const specDir = path.resolve(here, "../../docs/api");
const outDir = path.resolve(here, "../types/api");

// Dev-only endpoints are never used by the console (DEC-055).
const SKIP = new Set(["dev.openapi.yaml"]);

const files = (await readdir(specDir))
  .filter((name) => name.endsWith(".openapi.yaml") && !SKIP.has(name))
  .sort();

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const header =
  "/**\n * Generated by scripts/generate-api-types.mjs from docs/api. Do not edit by hand.\n */\n\n";

for (const name of files) {
  // The backend always sends every field (missing values come as null), but the API files
  // rarely list `required`, so treat every field as present unless it says otherwise.
  const ast = await openapiTS(pathToFileURL(path.join(specDir, name)), {
    propertiesRequiredByDefault: true,
  });
  const outName = name.replace(".openapi.yaml", ".ts");
  await writeFile(path.join(outDir, outName), header + astToString(ast));
  console.log(`types/api/${outName}`);
}

console.log(`Done: ${files.length} files.`);
